#!/usr/bin/env node
// Copy the OpenMoji drawings for every emoji the picker offers into
// public/emoji, and generate the list the app checks at render time.
//
//     node scripts/build-emoji-assets.mjs
//
// Why files rather than a sprite, which is how the icons ship: there are
// 550-odd emoji at ~3KB each, so one sprite would be 1.6MB downloaded on
// every first load. As separate files a screen fetches only the dozen or
// so it actually shows, and the browser caches them.
//
// Emoji stay stored as the character itself. This only changes what gets
// drawn — the same "🍜" that used to render in the system font.
//
// LICENCE: OpenMoji is CC BY-SA 4.0. The credit line is required, and it
// lives in the settings screen (settings.emojiCredit) with the full text
// copied to public/emoji/LICENSE.txt. Do not drop either.

import { readFile, writeFile, mkdir, copyFile, readdir, rm, stat } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const GROUPS_TS = join(ROOT, 'src', 'components', 'icons', 'emoji-groups.ts');
const OPENMOJI_DIR = join(ROOT, 'node_modules', 'openmoji', 'color', 'svg');
const OPENMOJI_LICENCE = join(ROOT, 'node_modules', 'openmoji', 'LICENSE.txt');
const OUT_DIR = join(ROOT, 'public', 'emoji');
const OUT_TS = join(ROOT, 'src', 'components', 'icons', 'emoji-assets.ts');

/**
 * Canonical file name for an emoji: code points in lowercase hex joined
 * by "-", with U+FE0F dropped.
 *
 * That selector only tells a font to render in colour, and it turns up
 * inconsistently in stored data — "🏷️" and "🏷" are one pick to the
 * person who made it. OpenMoji drops it from its own file names too, so
 * this is the same rule on both sides.
 *
 * Kept byte-identical to emojiAssetName() in emoji-asset.ts. If one
 * changes the other has to.
 */
function assetName(emoji) {
  return [...emoji]
    .map((ch) => ch.codePointAt(0))
    .filter((cp) => cp !== 0xfe0f)
    .map((cp) => cp.toString(16))
    .join('-');
}

/** Pull every emoji out of the generated-adjacent groups module. */
async function readPickerEmoji() {
  const src = await readFile(GROUPS_TS, 'utf8');
  const arrays = [...src.matchAll(/emojis: \[([\s\S]*?)\]/g)];
  if (arrays.length === 0) throw new Error('no emoji arrays found in emoji-groups.ts');
  const all = arrays.flatMap((m) => [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]));
  return [...new Set(all)];
}

async function main() {
  const emoji = await readPickerEmoji();

  // Start from empty so an emoji removed from the picker stops shipping.
  await rm(OUT_DIR, { recursive: true, force: true });
  await mkdir(OUT_DIR, { recursive: true });

  const names = [];
  const missing = [];
  let bytes = 0;

  for (const char of emoji) {
    const name = assetName(char);
    if (names.includes(name)) continue;
    // OpenMoji drops U+FE0F from a plain emoji's file name but keeps it
    // inside a ZWJ sequence — 1F3F7.svg, yet 1F43B-200D-2744-FE0F.svg. So
    // try the stripped spelling, then the full one. What we write out is
    // always the stripped name, so the runtime rule stays a single step.
    const spellings = [
      name.toUpperCase(),
      [...char].map((ch) => ch.codePointAt(0).toString(16).toUpperCase()).join('-'),
    ];
    let copied = false;
    for (const spelling of spellings) {
      const source = join(OPENMOJI_DIR, `${spelling}.svg`);
      try {
        await copyFile(source, join(OUT_DIR, `${name}.svg`));
        bytes += (await stat(source)).size;
        names.push(name);
        copied = true;
        break;
      } catch {
        // try the next spelling
      }
    }
    // Not fatal: the app falls back to the system font glyph for any
    // emoji it has no drawing for, which is how it behaved before.
    if (!copied) missing.push(`${char} (${name})`);
  }

  await copyFile(OPENMOJI_LICENCE, join(OUT_DIR, 'LICENSE.txt'));

  const ts = `// Auto-generated by scripts/build-emoji-assets.mjs — do not edit by hand.
// ${names.length} emoji drawn from OpenMoji (CC BY-SA 4.0), served from
// /emoji/<name>.svg. Anything not listed falls back to the system font.

export const EMOJI_ASSETS = [
${names.map((n) => `  "${n}",`).join('\n')}
] as const;
`;
  await writeFile(OUT_TS, ts, 'utf8');

  const files = (await readdir(OUT_DIR)).filter((f) => f.endsWith('.svg'));
  console.log(
    `public/emoji: ${files.length} files, ${(bytes / 1024).toFixed(0)}KB total`
  );
  if (missing.length) {
    console.log(`no OpenMoji drawing for ${missing.length}: ${missing.join(', ')}`);
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
