#!/usr/bin/env node
// Build SVG sprite from Sticker Pop section HTML files.
// Source: ~/Documents/jaitang-icons-final/sticker/0{1,2,3,4,6}-*.html
// Output: public/icons-sticker.svg + src/components/icons/icon-names.ts

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = join(homedir(), 'Documents', 'jaitang-icons-final', 'sticker');
const OUT_SPRITE = join(ROOT, 'public', 'icons-sticker.svg');
const OUT_TYPES = join(ROOT, 'src', 'components', 'icons', 'icon-names.ts');

const SECTIONS = [
  '01-navigation.html',
  '02-action.html',
  '03-status.html',
  '04-domain.html',
  // Section 5 has no master sprite — its icons come from per-pair mini files.
  // Order doesn't matter functionally but Account / Trip / Goal / Category
  // groups the picker palettes the same way the UI exposes them.
  '05-emoji-account-mini-a.html',
  '05-emoji-account-mini-b.html',
  '05-emoji-account-mini-c.html',
  '05-emoji-account-mini-d.html',
  '05-emoji-trip-mini-a.html',
  '05-emoji-trip-mini-b.html',
  '05-emoji-trip-mini-c.html',
  '05-emoji-trip-mini-d.html',
  '05-emoji-trip-mini-e.html',
  '05-emoji-goal-mini-a.html',
  '05-emoji-goal-mini-b.html',
  '05-emoji-goal-mini-c.html',
  '05-emoji-goal-mini-d.html',
  '05-emoji-category-mini-a.html',
  '05-emoji-category-mini-b.html',
  '06-future.html',
];

const SYMBOL_RE = /<symbol\s+id="(ic-[a-z0-9-]+)"[\s\S]*?<\/symbol>/g;

// Each Sticker Pop symbol defines internal gradient IDs like `bell-body`.
// Some are shared across symbols (e.g. `ar-body` is reused 3x), which breaks
// SVG rendering because `url(#ar-body)` resolves to the first occurrence.
// Namespace every internal id by suffixing the symbol id, then update
// `url(#...)` and `href="#..."` references inside the same block.
function namespaceInternalIds(block, symbolId) {
  const internalIds = [];
  const idRe = /\bid="([a-zA-Z][\w-]*)"/g;
  let m;
  while ((m = idRe.exec(block)) !== null) {
    if (m[1] !== symbolId) internalIds.push(m[1]);
  }
  let out = block;
  for (const id of internalIds) {
    const ns = `${id}__${symbolId.replace(/^ic-/, '')}`;
    out = out
      .replaceAll(`id="${id}"`, `id="${ns}"`)
      .replaceAll(`url(#${id})`, `url(#${ns})`)
      .replaceAll(`href="#${id}"`, `href="#${ns}"`)
      .replaceAll(`xlink:href="#${id}"`, `xlink:href="#${ns}"`);
  }
  return out;
}

const symbols = [];
const names = new Set();
const collisions = [];

for (const file of SECTIONS) {
  const path = join(SRC_DIR, file);
  const html = await readFile(path, 'utf8');
  let match;
  let count = 0;
  while ((match = SYMBOL_RE.exec(html)) !== null) {
    const [block, id] = match;
    if (names.has(id)) {
      collisions.push(`${id} (in ${file})`);
      continue;
    }
    names.add(id);
    symbols.push(namespaceInternalIds(block, id));
    count++;
  }
  console.log(`  ${file}: ${count} symbols`);
}

if (collisions.length) {
  console.warn(`\n⚠️  Skipped ${collisions.length} duplicate ids:`);
  collisions.forEach((c) => console.warn(`     - ${c}`));
}

const sprite = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">
<defs>
${symbols.join('\n')}
</defs>
</svg>
`;

await mkdir(dirname(OUT_SPRITE), { recursive: true });
await writeFile(OUT_SPRITE, sprite, 'utf8');

const iconNames = [...names].map((id) => id.replace(/^ic-/, '')).sort();
const types = `// Auto-generated by scripts/build-icon-sprite.mjs — do not edit by hand.
// ${iconNames.length} icons from Sticker Pop sprite.

export const ICON_NAMES = ${JSON.stringify(iconNames, null, 2)} as const;

export type IconName = (typeof ICON_NAMES)[number];
`;

await mkdir(dirname(OUT_TYPES), { recursive: true });
await writeFile(OUT_TYPES, types, 'utf8');

const spriteBytes = (await readFile(OUT_SPRITE)).length;
console.log(`\n✅ ${symbols.length} symbols → ${OUT_SPRITE} (${(spriteBytes / 1024).toFixed(1)} KB)`);
console.log(`✅ ${iconNames.length} icon names → ${OUT_TYPES}`);
